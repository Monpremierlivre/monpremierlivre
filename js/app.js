  // ---- Blog sidebar category filter ----
  function initBlogFilter(){
    var links = document.querySelectorAll("[data-blog-filter]");
    var grid = document.querySelector("[data-blog-grid]");
    if(!links.length || !grid) return;
    var cards = grid.querySelectorAll(".blog-card");

    links.forEach(function(a){
      a.addEventListener("click", function(e){
        e.preventDefault();
        var cat = a.getAttribute("data-blog-filter");
        links.forEach(function(l){ l.classList.toggle("active", l === a); });
        cards.forEach(function(card){
          var show = cat === "all" || card.getAttribute("data-category") === cat;
          card.style.display = show ? "" : "none";
        });
      });
    });
  }

  // ---- FAQ sidebar nav (click-to-jump + scroll-spy) ----
  function initFaqNav(){
    var navLinks = document.querySelectorAll("[data-faq-nav]");
    if(!navLinks.length) return;
    var cats = Array.prototype.map.call(navLinks, function(a){
      return document.getElementById(a.getAttribute("data-faq-nav"));
    });

    navLinks.forEach(function(a){
      a.addEventListener("click", function(e){
        e.preventDefault();
        var target = document.getElementById(a.getAttribute("data-faq-nav"));
        if(target) target.scrollIntoView({behavior:"smooth", block:"start"});
      });
    });

    function setActive(id){
      navLinks.forEach(function(a){
        a.classList.toggle("active", a.getAttribute("data-faq-nav") === id);
      });
    }
    setActive(cats[0] && cats[0].id);

    window.addEventListener("scroll", function(){
      var pos = window.scrollY + 130;
      var current = cats[0];
      cats.forEach(function(cat){
        if(cat && cat.offsetTop <= pos) current = cat;
      });
      if(current) setActive(current.id);
    }, {passive:true});
  }

  // ---- Auth tabs (compte.html) ----
  function initAuthTabs(){
    var tabs = document.querySelectorAll(".auth-tabs button");
    if(!tabs.length) return;
    tabs.forEach(function(btn){
      btn.addEventListener("click", function(){
        tabs.forEach(function(b){ b.classList.remove("active"); });
        btn.classList.add("active");
        document.querySelectorAll(".auth-panel").forEach(function(p){
          p.style.display = p.getAttribute("data-panel") === btn.getAttribute("data-tab") ? "block" : "none";
        });
      });
    });
  }

  // ---- Bandeau promo -10% (toujours visible en haut, au-dessus du header) ----
  function initPromoBanner(){
    if(document.querySelector(".promo-banner")) return; // évite les doublons si appelé 2 fois
    var banner = document.createElement("a");
    banner.href = "compte.html";
    banner.className = "promo-banner";
    banner.innerHTML = '<span data-i18n="promo_banner_text"></span>';
    document.body.insertBefore(banner, document.body.firstChild);
    var header = document.querySelector(".site-header");
    function syncOffset(){
      if(header) header.style.top = banner.offsetHeight + "px";
    }
    syncOffset();
    window.addEventListener("resize", syncOffset);
  }

  // ---- Mobile nav ----
  function initBurger(){
    var burger = document.querySelector(".burger");
    var navs = document.querySelectorAll(".main-nav");
    if(!burger || !navs.length) return;
    var wrap = document.createElement("div");
    wrap.style.cssText = "display:none;position:absolute;top:104px;left:0;right:0;flex-direction:column;gap:14px;background:var(--cream);padding:16px 24px;border-bottom:1px solid var(--border);z-index:90";
    navs.forEach(function(nav){
      nav.querySelectorAll("a").forEach(function(a){ wrap.appendChild(a.cloneNode(true)); });
    });
    document.querySelector(".site-header").appendChild(wrap);
    burger.addEventListener("click", function(){
      wrap.style.display = wrap.style.display === "flex" ? "none" : "flex";
    });
  }

  // ---- Page flip transition ----
  // A dedicated overlay panel (styled like a paper page, hinged on its left
  // edge) swings OPEN on every page load, sweeping from right to left to
  // reveal the page underneath, like turning to this page in a book.
  function initPageFlip(){
    var overlay = document.createElement("div");
    overlay.id = "flip-overlay";
    document.body.appendChild(overlay);

    requestAnimationFrame(function(){
      overlay.classList.add("flip-open");
    });
  }

