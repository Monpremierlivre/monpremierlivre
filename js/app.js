  function getLang(){ return localStorage.getItem("mpl_lang") || "fr"; }
  function setLang(l){
    localStorage.setItem("mpl_lang", l);
    applyLang();
    renderCartPage();
  }

  function applyLang(){
    var lang = getLang();
    document.documentElement.setAttribute("lang", lang);
    var dict = I18N[lang] || I18N.fr;
    document.querySelectorAll("[data-i18n]").forEach(function(el){
      var key = el.getAttribute("data-i18n");
      if(dict[key]) el.innerHTML = dict[key];
    });
    document.querySelectorAll(".lang-toggle button").forEach(function(btn){
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
    document.querySelectorAll("[data-fr-only]").forEach(function(el){
      el.style.display = lang === "fr" ? "" : "none";
    });
    document.querySelectorAll("[data-en-note]").forEach(function(el){
      el.style.display = lang === "en" ? "" : "none";
    });
    document.querySelectorAll("[data-lang-block]").forEach(function(el){
      el.style.display = el.getAttribute("data-lang-block") === lang ? "" : "none";
    });
  }

  function initLangToggle(){
    document.querySelectorAll(".lang-toggle button").forEach(function(btn){
      btn.addEventListener("click", function(){ setLang(btn.getAttribute("data-lang")); });
    });
  }

  // ---- Cart & wishlist (localStorage demo) ----
  function getCart(){ try{ return JSON.parse(localStorage.getItem("mpl_cart")||"[]"); }catch(e){ return []; } }
  function saveCart(c){ localStorage.setItem("mpl_cart", JSON.stringify(c)); updateBadges(); }
  function getWishlist(){ try{ return JSON.parse(localStorage.getItem("mpl_wishlist")||"[]"); }catch(e){ return []; } }
  function saveWishlist(w){ localStorage.setItem("mpl_wishlist", JSON.stringify(w)); updateBadges(); }

  function addToCart(slug, name, price, qty){
    qty = qty || 1;
    var cart = getCart();
    var line = cart.find(function(l){ return l.slug === slug; });
    if(line){ line.qty += qty; } else { cart.push({slug:slug, name:name, price:price, qty:qty}); }
    saveCart(cart);
  }
  function toggleWishlist(slug, name, price){
    var w = getWishlist();
    var idx = w.findIndex(function(l){ return l.slug === slug; });
    if(idx > -1){ w.splice(idx,1); } else { w.push({slug:slug,name:name,price:price}); }
    saveWishlist(w);
    return idx === -1;
  }
  function isWishlisted(slug){ return getWishlist().some(function(l){ return l.slug === slug; }); }

  function updateBadges(){
    var cart = getCart();
    var count = cart.reduce(function(a,l){ return a + l.qty; }, 0);
    document.querySelectorAll("[data-cart-badge]").forEach(function(el){
      el.textContent = count;
      el.style.display = count > 0 ? "flex" : "none";
    });
  }

  function initWishlistButtons(){
    document.querySelectorAll("[data-wishlist-slug]").forEach(function(btn){
      var slug = btn.getAttribute("data-wishlist-slug");
      if(isWishlisted(slug)) btn.classList.add("active");
      if(btn.dataset.boundWishlist) return;
      btn.dataset.boundWishlist = "1";
      btn.addEventListener("click", function(e){
        e.preventDefault();
        var name = btn.getAttribute("data-name");
        var price = parseFloat(btn.getAttribute("data-price"));
        var added = toggleWishlist(slug, name, price);
        btn.classList.toggle("active", added);
      });
    });
  }

  function initCartButtons(){
    document.querySelectorAll("[data-add-cart]").forEach(function(btn){
      if(btn.dataset.boundCart) return;
      btn.dataset.boundCart = "1";
      btn.addEventListener("click", function(){
        var slug = btn.getAttribute("data-add-cart");
        var name = btn.getAttribute("data-name");
        var price = parseFloat(btn.getAttribute("data-price"));
        var qtyEl = document.querySelector("[data-qty-value]");
        var qty = qtyEl ? parseInt(qtyEl.textContent,10) : 1;
        addToCart(slug, name, price, qty);
        var dict = I18N[getLang()] || I18N.fr;
        var label = dict.added_ok || "Ajouté !";
        var original = btn.textContent;
        btn.textContent = label;
        setTimeout(function(){ btn.textContent = original; }, 1400);
      });
    });
    document.querySelectorAll("[data-buy-now]").forEach(function(btn){
      if(btn.dataset.boundCart) return;
      btn.dataset.boundCart = "1";
      btn.addEventListener("click", function(){
        var slug = btn.getAttribute("data-buy-now");
        var name = btn.getAttribute("data-name");
        var price = parseFloat(btn.getAttribute("data-price"));
        var qtyEl = document.querySelector("[data-qty-value]");
        var qty = qtyEl ? parseInt(qtyEl.textContent,10) : 1;
        addToCart(slug, name, price, qty);
        window.location.href = "/panier.html";
      });
    });
  }

  function initQtySelector(){
    var minus = document.querySelector("[data-qty-minus]");
    var plus = document.querySelector("[data-qty-plus]");
    var val = document.querySelector("[data-qty-value]");
    if(!val) return;
    if(val.dataset.boundQty) return;
    val.dataset.boundQty = "1";
    minus && minus.addEventListener("click", function(){
      var v = Math.max(1, parseInt(val.textContent,10)-1);
      val.textContent = v;
    });
    plus && plus.addEventListener("click", function(){
      var v = parseInt(val.textContent,10)+1;
      val.textContent = v;
    });
  }

  function renderCartPage(){
    var container = document.querySelector("[data-cart-list]");
    if(!container) return;
    var cart = getCart();
    var lang = getLang();
    var dict = I18N[lang] || I18N.fr;
    var summary = document.querySelector("[data-cart-summary]");
    if(cart.length === 0){
      container.innerHTML = '<div class="empty-state"><p>'+dict.cart_empty+'</p></div>';
      if(summary) summary.style.display = "none";
      return;
    }
    var html = "";
    var subtotal = 0;
    cart.forEach(function(line, i){
      subtotal += line.price * line.qty;
      html += '<div class="cart-line">'
        + '<div class="media"><i class="ti ti-book-2"></i></div>'
        + '<div class="grow"><h4>'+line.name+'</h4>'
        +   '<div class="qty-selector" style="margin-top:8px"><button data-line-minus="'+i+'" type="button">−</button><span data-line-qty="'+i+'">'+line.qty+'</span><button data-line-plus="'+i+'" type="button">+</button></div>'
        + '</div>'
        + '<div class="price">'+(line.price*line.qty).toFixed(2)+' €</div>'
        + '<button class="btn btn-ghost btn-small" data-remove-line="'+i+'">'+dict.cart_remove+'</button>'
        + '</div>';
    });
    container.innerHTML = html;
    container.querySelectorAll("[data-remove-line]").forEach(function(btn){
      btn.addEventListener("click", function(){
        var idx = parseInt(btn.getAttribute("data-remove-line"),10);
        var c = getCart();
        c.splice(idx,1);
        saveCart(c);
        renderCartPage();
      });
    });
    container.querySelectorAll("[data-line-minus]").forEach(function(btn){
      btn.addEventListener("click", function(){
        var idx = parseInt(btn.getAttribute("data-line-minus"),10);
        var c = getCart();
        if(!c[idx]) return;
        if(c[idx].qty <= 1){
          c.splice(idx,1);
        } else {
          c[idx].qty -= 1;
        }
        saveCart(c);
        renderCartPage();
      });
    });
    container.querySelectorAll("[data-line-plus]").forEach(function(btn){
      btn.addEventListener("click", function(){
        var idx = parseInt(btn.getAttribute("data-line-plus"),10);
        var c = getCart();
        if(!c[idx]) return;
        c[idx].qty += 1;
        saveCart(c);
        renderCartPage();
      });
    });
    var shipping = subtotal >= 80 ? 0 : 4.9;
    document.querySelector("[data-sum-subtotal]").textContent = subtotal.toFixed(2) + " €";
    document.querySelector("[data-sum-shipping]").textContent = shipping === 0 ? dict.cart_free : shipping.toFixed(2) + " €";
    document.querySelector("[data-sum-total]").textContent = (subtotal + shipping).toFixed(2) + " €";
  }

